export function ServiceIcon({ id, size = 22 }) {
  switch (id) {
    case 'structure':
      return <SofaIcon size={size} />;
    case 'upholstery':
      return <FabricIcon size={size} />;
    case 'reupholstery':
      return <RestoreIcon size={size} />;
    case 'bed':
      return <BedIcon size={size} />;
    case 'cover':
      return <CoverIcon size={size} />;
    case 'mattress':
      return <MattressIcon size={size} />;
    case 'curtains':
      return <CurtainIcon size={size} />;
    case 'material':
      return <RulerIcon size={size} />;
    default:
      return <SofaIcon size={size} />;
  }
}
